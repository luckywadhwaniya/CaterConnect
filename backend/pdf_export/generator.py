# Register Indian / Unicode fonts if available on the system
FONT_REGULAR = 'Helvetica'
FONT_BOLD = 'Helvetica-Bold'

FONT_CANDIDATES = [
    ('NirmalaUI', r'C:\Windows\Fonts\Nirmala.ttf', r'C:\Windows\Fonts\NirmalaB.ttf'),
    ('Shruti', r'C:\Windows\Fonts\Shruti.ttf', r'C:\Windows\Fonts\Shrutib.ttf'),
    ('ArialUnicode', r'C:\Windows\Fonts\arialuni.ttf', r'C:\Windows\Fonts\arialuni.ttf'),
]

for font_family, reg_path, bold_path in FONT_CANDIDATES:
    if os.path.exists(reg_path):
        try:
            pdfmetrics.registerFont(TTFont(font_family, reg_path))
            FONT_REGULAR = font_family
            if os.path.exists(bold_path):
                pdfmetrics.registerFont(TTFont(f"{font_family}-Bold", bold_path))
                FONT_BOLD = f"{font_family}-Bold"
            else:
                FONT_BOLD = font_family
            break
        except Exception:
            pass


class NumberedCanvas(canvas.Canvas):
    """Canvas that computes total pages and adds a professional footer."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages):
        self.saveState()
        self.setFont(FONT_REGULAR, 8)
        self.setFillColor(colors.HexColor('#6b7280'))

        # Top decorative thin bar
        self.setFillColor(colors.HexColor('#059669'))
        self.rect(36, A4[1] - 12, A4[0] - 72, 3, stroke=0, fill=1)

        # Footer divider line
        self.setStrokeColor(colors.HexColor('#e5e7eb'))
        self.setLineWidth(0.5)
        self.line(36, 40, A4[0] - 36, 40)

        # Footer texts
        self.setFont(FONT_REGULAR, 8)
        self.setFillColor(colors.HexColor('#6b7280'))
        self.drawString(36, 28, "Generated by CaterConnect • Grocery & Catering Logistics Platform")
        page_str = f"Page {self._pageNumber} of {total_pages}"
        self.drawRightString(A4[0] - 36, 28, page_str)
        self.restoreState()


def format_text_safe(text, fallback=""):
    """Format text safely to avoid font encoding errors if fallback is required."""
    if not text:
        return fallback
    clean = str(text).strip()
    return clean


def generate_order_pdf(order):
    """
    Generate a clean, high-grade PDF document for a CaterConnect grocery order.
    Returns a BytesIO buffer seeked to 0.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=36,
        rightMargin=36,
        topMargin=36,
        bottomMargin=54,
    )

    primary_color = colors.HexColor('#059669')  # Emerald Green
    secondary_color = colors.HexColor('#065f46')
    bg_light = colors.HexColor('#f0fdf4')
    border_color = colors.HexColor('#d1fae5')
    text_dark = colors.HexColor('#111827')
    text_muted = colors.HexColor('#4b5563')

    styles = getSampleStyleSheet()

    # Custom typography styles
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Normal'],
        fontName=FONT_BOLD,
        fontSize=24,
        leading=28,
        textColor=primary_color,
    )
    tagline_style = ParagraphStyle(
        'DocTagline',
        parent=styles['Normal'],
        fontName=FONT_REGULAR,
        fontSize=9,
        leading=12,
        textColor=text_muted,
    )
    header_right_style = ParagraphStyle(
        'HeaderRight',
        parent=styles['Normal'],
        fontName=FONT_BOLD,
        fontSize=12,
        leading=16,
        alignment=TA_RIGHT,
        textColor=secondary_color,
    )
    badge_style = ParagraphStyle(
        'BadgeStyle',
        parent=styles['Normal'],
        fontName=FONT_BOLD,
        fontSize=9,
        leading=12,
        alignment=TA_RIGHT,
        textColor=colors.HexColor('#047857'),
    )
    section_heading = ParagraphStyle(
        'SectionHeading',
        parent=styles['Normal'],
        fontName=FONT_BOLD,
        fontSize=11,
        leading=15,
        textColor=secondary_color,
        spaceAfter=6,
    )
    card_label = ParagraphStyle(
        'CardLabel',
        parent=styles['Normal'],
        fontName=FONT_BOLD,
        fontSize=8,
        leading=11,
        textColor=colors.HexColor('#374151'),
    )
    card_value = ParagraphStyle(
        'CardValue',
        parent=styles['Normal'],
        fontName=FONT_REGULAR,
        fontSize=9,
        leading=12,
        textColor=text_dark,
    )
    table_cell = ParagraphStyle(
        'TableCell',
        parent=styles['Normal'],
        fontName=FONT_REGULAR,
        fontSize=8.5,
        leading=11.5,
        textColor=text_dark,
    )
    table_cell_bold = ParagraphStyle(
        'TableCellBold',
        parent=styles['Normal'],
        fontName=FONT_BOLD,
        fontSize=8.5,
        leading=11.5,
        textColor=text_dark,
    )
    table_header_style = ParagraphStyle(
        'TableHeader',
        parent=styles['Normal'],
        fontName=FONT_BOLD,
        fontSize=9,
        leading=12,
        textColor=colors.white,
    )

    story = []

    # 1. HEADER SECTION
    created_date_str = order.created_at.strftime('%d %b %Y, %I:%M %p') if order.created_at else timezone.now().strftime('%d %b %Y')
    status_label = order.get_status_display().upper()

    header_left = [
        Paragraph("CaterConnect", title_style),
        Paragraph("Event Grocery & Supplies Logistics Order", tagline_style),
    ]
    header_right = [
        Paragraph(f"Order #{order.order_number}", header_right_style),
        Paragraph(f"Status: {status_label}", badge_style),
        Paragraph(f"Date: {created_date_str}", tagline_style),
    ]

    header_table = Table(
        [[header_left, header_right]],
        colWidths=[310, 213],
    )
    header_table.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 10),
    ]))
    story.append(header_table)

    story.append(HRFlowable(width="100%", thickness=1.5, color=primary_color, spaceAfter=14))

    # 2. EVENT & CONTACT CARDS (2 Columns)
    event = getattr(order, 'event', None)
    event_name = event.event_name if event else "N/A"
    event_date = event.event_date.strftime('%d %b %Y') if (event and event.event_date) else "N/A"
    delivery_date = event.delivery_date.strftime('%d %b %Y') if (event and event.delivery_date) else "N/A"
    delivery_time = event.delivery_time.strftime('%I:%M %p') if (event and event.delivery_time) else "N/A"
    event_loc = event.event_location if event else "N/A"
    guests = str(event.num_guests) if event else "N/A"

    catering_user = order.catering_user
    caterer_name = catering_user.full_name if catering_user else "N/A"
    profile = getattr(catering_user, 'catering_profile', None)
    caterer_business = profile.business_name if profile and profile.business_name else caterer_name
    caterer_phone = profile.phone if profile and profile.phone else "N/A"
    caterer_email = catering_user.email if catering_user else "N/A"

    store = order.store
    store_name = store.store_name if store else "N/A"
    store_phone = store.phone if store and store.phone else "N/A"
    store_address = store.address if store and store.address else "N/A"

    event_card_data = [
        [Paragraph("EVENT DETAILS", section_heading), ""],
        [Paragraph("Event Name:", card_label), Paragraph(event_name, card_value)],
        [Paragraph("Event Date:", card_label), Paragraph(event_date, card_value)],
        [Paragraph("Delivery Schedule:", card_label), Paragraph(f"{delivery_date} at {delivery_time}", card_value)],
        [Paragraph("Guest Count:", card_label), Paragraph(f"{guests} Guests", card_value)],
        [Paragraph("Venue / Location:", card_label), Paragraph(event_loc, card_value)],
    ]
    event_table = Table(event_card_data, colWidths=[95, 155])
    event_table.setStyle(TableStyle([
        ('SPAN', (0, 0), (1, 0)),
        ('BACKGROUND', (0, 0), (-1, -1), bg_light),
        ('BOX', (0, 0), (-1, -1), 0.5, border_color),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
        ('LINEBELOW', (0, 0), (-1, 0), 1, primary_color),
    ]))

    contacts_card_data = [
        [Paragraph("PARTIES & CONTACTS", section_heading), ""],
        [Paragraph("Caterer:", card_label), Paragraph(f"<b>{caterer_business}</b><br/>{caterer_name}<br/>Ph: {caterer_phone}<br/>{caterer_email}", card_value)],
        [Paragraph("Grocery Store:", card_label), Paragraph(f"<b>{store_name}</b><br/>Ph: {store_phone}<br/>{store_address}", card_value)],
    ]
    contacts_table = Table(contacts_card_data, colWidths=[80, 170])
    contacts_table.setStyle(TableStyle([
        ('SPAN', (0, 0), (1, 0)),
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#f9fafb')),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#e5e7eb')),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
        ('LINEBELOW', (0, 0), (-1, 0), 1, colors.HexColor('#9ca3af')),
    ]))

    info_grid = Table([[event_table, contacts_table]], colWidths=[256, 256])
    info_grid.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 12),
    ]))
    story.append(info_grid)

    # 3. GROCERY ITEMS TABLE
    is_billed = getattr(order, 'is_billed', False) or (getattr(order, 'total_amount', 0) and order.total_amount > 0)
    section_title = "TAX INVOICE & GROCERY LIST" if is_billed else "GROCERY REQUIREMENTS LIST"
    story.append(Paragraph(section_title, section_heading))

    if is_billed:
        table_data = [
            [
                Paragraph("#", table_header_style),
                Paragraph("Item Name / Description", table_header_style),
                Paragraph("Qty", table_header_style),
                Paragraph("Unit", table_header_style),
                Paragraph("Rate (₹)", table_header_style),
                Paragraph("Amount (₹)", table_header_style),
            ]
        ]
        col_widths = [24, 200, 48, 55, 80, 105]
    else:
        table_data = [
            [
                Paragraph("#", table_header_style),
                Paragraph("Item Name / Description", table_header_style),
                Paragraph("Quantity", table_header_style),
                Paragraph("Unit", table_header_style),
                Paragraph("Special Notes / Store Feedback", table_header_style),
            ]
        ]
        col_widths = [24, 215, 60, 65, 148]

    items = order.items.select_related('grocery_item').all()
    if items.exists():
        for idx, item in enumerate(items, start=1):
            gujarati_name = item.grocery_item.name if item.grocery_item else item.custom_item_name
            english_name = item.grocery_item.name_en if (item.grocery_item and item.grocery_item.name_en) else ""

            if english_name and english_name != gujarati_name:
                display_name = f"<b>{gujarati_name}</b> <font color='#4b5563'>({english_name})</font>"
            else:
                display_name = f"<b>{gujarati_name}</b>"

            notes_display = item.notes or ""
            if not item.is_available:
                alt = f" • Suggestion: {item.alternative_suggestion}" if item.alternative_suggestion else ""
                notes_display = f"<font color='#dc2626'><b>[UNAVAILABLE]</b></font> {notes_display}{alt}"

            qty_str = f"{item.quantity:g}" if hasattr(item.quantity, 'normalize') else str(item.quantity)

            if is_billed:
                unit_p = f"₹{float(item.unit_price):,.2f}" if getattr(item, 'unit_price', 0) else "—"
                tot_p = f"₹{float(item.computed_total):,.2f}" if getattr(item, 'computed_total', 0) else "—"
                table_data.append([
                    Paragraph(str(idx), table_cell),
                    Paragraph(display_name, table_cell),
                    Paragraph(qty_str, table_cell_bold),
                    Paragraph(item.get_unit_display() if hasattr(item, 'get_unit_display') else item.unit, table_cell),
                    Paragraph(unit_p, table_cell),
                    Paragraph(tot_p, table_cell_bold),
                ])
            else:
                table_data.append([
                    Paragraph(str(idx), table_cell),
                    Paragraph(display_name, table_cell),
                    Paragraph(qty_str, table_cell_bold),
                    Paragraph(item.get_unit_display() if hasattr(item, 'get_unit_display') else item.unit, table_cell),
                    Paragraph(notes_display or "-", table_cell),
                ])
    else:
        empty_row = [Paragraph("1", table_cell), Paragraph("No items added to this order.", table_cell)]
        empty_row.extend([Paragraph("-", table_cell)] * (len(col_widths) - 2))
        table_data.append(empty_row)

    items_table = Table(
        table_data,
        colWidths=col_widths,
        repeatRows=1,
    )
    items_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), primary_color),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('ALIGN', (0, 0), (0, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 4.5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4.5),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#f9fafb')]),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#e5e7eb')),
        ('BOX', (0, 0), (-1, -1), 1, primary_color),
    ]))
    story.append(items_table)

    # Billing Totals Summary block (if billed)
    if is_billed:
        subtot = float(getattr(order, 'subtotal_amount', 0) or 0)
        deliv = float(getattr(order, 'delivery_charge', 0) or 0)
        disc = float(getattr(order, 'discount_amount', 0) or 0)
        tot = float(getattr(order, 'total_amount', 0) or 0)

        bill_summary_rows = [
            [Paragraph("Items Subtotal:", card_label), Paragraph(f"₹{subtot:,.2f}", card_value)],
        ]
        if deliv > 0:
            bill_summary_rows.append([Paragraph("Delivery / Logistics:", card_label), Paragraph(f"₹{deliv:,.2f}", card_value)])
        if disc > 0:
            bill_summary_rows.append([Paragraph("Discount Applied:", card_label), Paragraph(f"-₹{disc:,.2f}", card_value)])
        bill_summary_rows.append([Paragraph("<b>FINAL BILL TOTAL:</b>", section_heading), Paragraph(f"<b><font size=11 color='#059669'>₹{tot:,.2f}</font></b>", section_heading)])

        bill_table = Table(bill_summary_rows, colWidths=[130, 100])
        bill_table.setStyle(TableStyle([
            ('ALIGN', (0, 0), (-1, -1), 'RIGHT'),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('TOPPADDING', (0, 0), (-1, -1), 3),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
            ('LINEABOVE', (0, -1), (-1, -1), 1, primary_color),
        ]))

        wrapper = Table([["", bill_table]], colWidths=[282, 230])
        wrapper.setStyle(TableStyle([('VALIGN', (0, 0), (-1, -1), 'TOP')]))
        story.append(Spacer(1, 6))
        story.append(wrapper)

    story.append(Spacer(1, 14))

    # 4. SPECIAL INSTRUCTIONS & STORE COMMENTS
    instructions_blocks = []
    if order.special_instructions:
        instructions_blocks.append(
            Paragraph("<b>Special Instructions from Caterer:</b>", card_label)
        )
        instructions_blocks.append(
            Paragraph(order.special_instructions, card_value)
        )
        instructions_blocks.append(Spacer(1, 6))

    if order.store_comment:
        instructions_blocks.append(
            Paragraph("<b>Comments / Notes from Store:</b>", card_label)
        )
        instructions_blocks.append(
            Paragraph(order.store_comment, card_value)
        )

    if instructions_blocks:
        inst_table = Table([[instructions_blocks]], colWidths=[512])
        inst_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#fffbeb')),  # warm light amber
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#fde68a')),
            ('TOPPADDING', (0, 0), (-1, -1), 8),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
            ('LEFTPADDING', (0, 0), (-1, -1), 10),
            ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ]))
        story.append(KeepTogether(inst_table))

    # Build the document using custom NumberedCanvas for footer
    doc.build(story, canvasmaker=NumberedCanvas)
    buffer.seek(0)
    return buffer
